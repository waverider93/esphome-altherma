"""Builds web/altherma-card.js, a Home Assistant dashboard card that shows web/altherma.html.

Run after changing the page:  python3 tools/make_ha_card.py
The card uses the page's markup, styles and script unchanged where it can; instead of polling values.json it builds
the same data from Home Assistant entities (see the header of the generated file).
The page is derived from the ESPAltherma web interface (MIT License, Copyright (c) 2020 Raomin).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "components" / "daikin_x10a"))
import catalog  # noqa: E402

LANGUAGES = ["en", "de", "fr", "it", "es"]


def cut(text, start, end):
    i = text.index(start) + len(start)
    return text[i:text.index(end, i)]


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise SystemExit(f"expected {old!r} once in the page, found {text.count(old)}")
    return text.replace(old, new)


def styles(html):
    css = cut(html, "<style>", "</style>")
    # The page's colour tokens live on the card; Home Assistant's dark theme switches them, not the browser
    dark = re.search(r"@media \(prefers-color-scheme:dark\)\{:root\{(.*?)\}\}", css, re.S)
    css = css.replace(dark.group(0), "")
    css = replace_once(css, ":root{", ":host{display:block;")
    css += ":host([dark]){" + dark.group(1) + "}"
    css = re.sub(r"\nhtml\{[^}]*\}", "", css)
    css = replace_once(css, "\nbody{", "\n.page{")
    css += ".back{display:none}table{color:inherit}"
    return css


def markup(html):
    return '<div class="page">' + cut(html, "<body>", "<script>") + "</div>"


def script(html):
    js = cut(html, "<script>", "</script>")
    for old, new in [
        ("document.querySelector(", "root.querySelector("),
        ("document.documentElement.lang = lang;", "host.lang = lang;"),
        ("document.createTreeWalker(document.body,", "document.createTreeWalker(root,"),
        ("getComputedStyle(document.documentElement)", "getComputedStyle(host)"),
        ("DK.addEventListener('change', paint);", ""),
        # Home Assistant formats the states in its language ("21,5 °C", "An"); the drawing reads the raw values
        ("v.v === '' ? '—' : v.v", "v.d != null ? v.d : v.v === '' ? '—' : v.v"),
    ]:
        js = replace_once(js, old, new)
    js = js.replace("document.getElementById(", "root.getElementById(")
    # values.json is replaced by update(), called by the card with the same data
    tail = js[js.index("async function poll() {"):]
    js = js.replace(tail, """function update(d) {
  setLang(pick(d.lang) || browserLang());
  model = String(d.model || '');
  tx('hdrModel', model);
  root.getElementById('nc').hidden = d.connected !== false;
  renderValues(Array.isArray(d.values) ? d.values : []);
  renderControl(d.control);
}
lang = browserLang();
translatePage();
renderValues([]);
return {update, reading};
""")
    return js


def keys(html):
    """The page's KEYS regexes, for finding the labels the drawing uses."""
    body = cut(html, "const KEYS = {", "};")
    return [re.compile(m, re.I) for m in re.findall(r"\w+: /(.*?)/i", body)]


def labels(html):
    """English label -> {language: name} for the labels the drawing uses."""
    regexes = keys(html)
    return {e.label: {lang: catalog.translate(e.label, lang) for lang in LANGUAGES}
            for e in catalog.entries() if any(r.search(e.label) for r in regexes)}


def names(html):
    """Entity name (any language, and the names the example YAML gives) -> English label, for the labels the
    drawing uses. ESPHome names entities after the label in the hub language; the card maps them back."""
    out = {}
    for label, local in labels(html).items():
        for name in local.values():
            out.setdefault(name, label)
    example = (ROOT / "examples" / "altherma-ech2o.yaml").read_text()
    for label, name in re.findall(r'label: "([^"]+)"\n(?:\s+register: \S+\n)?\s+name: (.+)', example):
        out[name.strip()] = label
    return dict(sorted(out.items()))


def main():
    html = (ROOT / "web" / "altherma.html").read_text()
    template = (ROOT / "web" / "altherma-card.template.js").read_text()
    card = (template
            .replace("/*GENERATED*/", "// Generated by tools/make_ha_card.py from web/altherma-card.template.js and web/altherma.html - do not edit.")
            .replace("/*STYLE*/", json.dumps(styles(html), ensure_ascii=False))
            .replace("/*MARKUP*/", json.dumps(markup(html), ensure_ascii=False))
            .replace("/*NAMES*/", json.dumps(names(html), ensure_ascii=False))
            .replace("/*LABELS*/", json.dumps(labels(html), ensure_ascii=False))
            .replace("/*SCRIPT*/", script(html)))
    (ROOT / "web" / "altherma-card.js").write_text(card)
    print(f"altherma-card.js: {len(card)} bytes")


if __name__ == "__main__":
    main()
