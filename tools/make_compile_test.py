"""Writes tests/compile-diagram.yaml from examples/altherma-ech2o.yaml for builds without downloads.

WiFi, OTA and the ESPHome web dashboard need components from the Espressif registry; the test swaps them for
Ethernet and the bare web server (enough for the diagram page) and moves relay pins off the Ethernet pins.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
s = (ROOT / "examples" / "altherma-ech2o.yaml").read_text()


def drop_block(text, key):
    return re.sub(rf"^{key}:.*?(?=^\S)", "", text, flags=re.S | re.M)


for key in ("wifi", "ota", "web_server"):
    s = drop_block(s, key)
s = re.sub(r"^\s*web_server: \{sorting_group_id: \w+\}\n", "", s, flags=re.M)
s = re.sub(r"^# Local dashboard.*\n", "", s, flags=re.M)
s = s.replace("name: altherma\n", "name: x10a-diagram\n", 1)
for old, new in (("GPIO25", "GPIO13"), ("GPIO26", "GPIO14"), ("GPIO27", "GPIO4")):
    s = s.replace(f"relay_{'sg1' if old == 'GPIO25' else 'sg2' if old == 'GPIO26' else 'safety'}: {old}",
                  f"relay_{'sg1' if old == 'GPIO25' else 'sg2' if old == 'GPIO26' else 'safety'}: {new}")
s = ("# Generated by tools/make_compile_test.py from examples/altherma-ech2o.yaml - do not edit.\n"
     "# Ethernet and the bare web server instead of WiFi and the dashboard: builds without registry downloads.\n" + s)
s += """
ethernet:
  type: LAN8720
  mdc_pin: GPIO23
  mdio_pin: GPIO18
  clk:
    pin: GPIO0
    mode: CLK_EXT_IN
  phy_addr: 0

mdns:
  disabled: true

web_server_base:
"""
(ROOT / "tests" / "compile-diagram.yaml").write_text(s)
print("tests/compile-diagram.yaml written")
