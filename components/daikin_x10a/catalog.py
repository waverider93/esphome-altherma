"""Reads the label catalog (catalog_data.h) at build time.

catalog_data.h is generated by ESPAltherma's scripts/gen_catalog.py from its definition files
(MIT License, Copyright (c) 2020 Raomin). The firmware uses the same file, so the YAML is checked against exactly
what the ESP will read.

Command line:
    python3 catalog.py                     # models
    python3 catalog.py "<model>" [de]      # values of a model, with their names in a language
"""

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
import re
import sys

CATALOG = Path(__file__).with_name("catalog_data.h")
LANGUAGES = ("en", "de", "fr", "it", "es")
FLAG_RECOMMENDED = 1
FLAG_ALWAYS = 2


@dataclass(frozen=True)
class Model:
    index: int
    name: str
    family: str
    protocol: str


@dataclass(frozen=True)
class Entry:
    registry: int
    offset: int
    conv: int
    size: int
    label: str
    flags: int
    models: int

    def in_model(self, model):
        return (self.models >> model.index) & 1 == 1

    @property
    def recommended(self):
        return bool(self.flags & FLAG_RECOMMENDED)


_STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')


def _pool(text, name):
    """The strings of a "a" "\\0" "b" "\\0" pool, by byte offset."""
    body = re.search(r"static const char %s\[\] =\n(.*?)\n\s*;" % name, text, re.S).group(1)
    strings, offset = {}, 0
    for line in body.splitlines():
        parts = _STRING.findall(line)
        if not parts:
            continue
        s = parts[0].replace('\\"', '"').replace("\\\\", "\\")
        strings[offset] = s
        offset += len(s.encode("utf-8")) + 1
    return strings


@lru_cache(maxsize=None)
def _load():
    text = CATALOG.read_text(encoding="utf-8")
    models_body = re.search(r"CATALOG_MODELS\[CATALOG_MODEL_COUNT\] = \{(.*?)\n\};", text, re.S).group(1)
    models = [
        Model(i, m.group(1), m.group(2), m.group(3))
        for i, m in enumerate(re.finditer(r'\{"([^"]+)", \'(\w)\', \'(\w)\'', models_body))
    ]
    labels = _pool(text, "CATALOG_LABELS")
    entries_body = re.search(r"CATALOG_ENTRIES\[CATALOG_ENTRY_COUNT\] = \{(.*?)\n\};", text, re.S).group(1)
    entries = [
        Entry(int(m.group(1), 16), int(m.group(2)), int(m.group(3)), int(m.group(4)), labels[int(m.group(5))],
              int(m.group(6)), int(m.group(7), 16))
        for m in re.finditer(
            r"\{0x(\w+), (\d+), (\d+), (\d+), -?\d+, (\d+), (\d+), 0x(\w+)ULL\}", entries_body)
    ]
    translations = {}
    for code in LANGUAGES[1:]:
        up = code.upper()
        names = _pool(text, "CATALOG_NAMES_" + up)
        pairs = re.search(r"CATALOG_TR_%s\[\] = \{(.*?)\n\};" % up, text, re.S).group(1)
        translations[code] = {labels[int(a)]: names[int(b)] for a, b in re.findall(r"\{(\d+), (\d+)\}", pairs)}
    return models, entries, translations


def models():
    return _load()[0]


def model_names():
    return [m.name for m in models()]


def find_model(name):
    """A model by its full catalog name, or by the part in brackets ("ERGA E EHSH-X P30-50 E_EF series ...")."""
    for m in models():
        short = m.name[m.name.find("(") + 1:-1] if m.name.endswith(")") else m.name
        if name in (m.name, short):
            return m
    raise ValueError(f"Unknown model '{name}'")


def entries(model=None):
    """The values of a model (all models when None), without the refrigerant markers."""
    return [e for e in _load()[1] if not e.flags & FLAG_ALWAYS and (model is None or e.in_model(model))]


def translate(label, language):
    """The display name of a label in a language, the English label when there is none."""
    if language in (None, "en"):
        return label
    return _load()[2][language].get(label, label)


def english(label):
    """The English label for a label given in any language, None when unknown."""
    if any(e.label == label for e in _load()[1]):
        return label
    for table in _load()[2].values():
        for en, name in table.items():
            if name == label:
                return en
    return None


def find_label(model, label, registry=None):
    """The entries a label resolves to: one per model that has it (only `model` when given).

    Raises ValueError when the label is unknown, or appears in several registries of one model without `registry`.
    """
    en = english(label)
    if en is None:
        raise ValueError(f"Unknown label '{label}'")
    found = [e for e in entries(model) if e.label == en and (registry is None or e.registry == registry)]
    if not found:
        where = f"model '{model.name}'" if model else "any model"
        reg = f" in register 0x{registry:02X}" if registry is not None else ""
        raise ValueError(f"Label '{label}' not found{reg} for {where}")
    for m in [model] if model else models():
        regs = sorted({e.registry for e in found if e.in_model(m)})
        if len(regs) > 1:
            raise ValueError(
                f"Label '{en}' is in registers {', '.join(f'0x{r:02X}' for r in regs)} of '{m.name}': set 'register'")
    return found


def main(argv):
    if len(argv) < 2:
        for m in models():
            print(f"{m.name}  [protocol {m.protocol}]")
        return
    model = find_model(argv[1])
    language = argv[2] if len(argv) > 2 else "en"
    for e in entries(model):
        mark = "*" if e.recommended else " "
        print(f"{mark} 0x{e.registry:02X} {e.offset:3} conv {e.conv:3} size {e.size}  {translate(e.label, language)}")


if __name__ == "__main__":
    main(sys.argv)
